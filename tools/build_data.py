def main() -> None:
    hexagrams = build()
    DATA_DIR.mkdir(exist_ok=True)

    js_path = DATA_DIR / "hexagrams.js"
    header = (
        "/* 周易六十四卦本地数据\n"
        "   原文：周易经传（公有领域），数据整理自 ichingshifa（MIT License）\n"
        "   解读：本应用原创简短解读（含求事/求人/求财/求姻缘） */\n"
    )
    payload = json.dumps(hexagrams, ensure_ascii=False, indent=1)
    js_path.write_text(header + "window.HEXAGRAMS = " + payload + ";\n", encoding="utf-8")

    json_path = DATA_DIR / "hexagrams.json"
    json_path.write_text(payload + "\n", encoding="utf-8")

    print(f"wrote {js_path} ({js_path.stat().st_size} bytes)")
    print(f"wrote {json_path} ({json_path.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
